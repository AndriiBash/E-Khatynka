// Частка собівартості, яку вдається повернути з нерозпроданого залишку.
// 1 день придатності — повна втрата; довший строк — частину можна
// продати завтра зі знижкою.
function salvageFraction(shelfLifeDays) {
  if (shelfLifeDays === null || shelfLifeDays === undefined) return 0.3;
  if (shelfLifeDays <= 1) return 0;
  if (shelfLifeDays === 2) return 0.35;
  return 0.6;
}

